import assert from 'node:assert/strict'
import { balances, monthlySpending, parseRupees, validateEntry } from '../src/ledger.ts'
import type { Entry } from '../src/ledger.ts'
const entry = (overrides: Partial<Entry> = {}): Entry => ({ id: '1', kind: 'expense', amountPaise: 15000, date: '2026-11-16', description: 'Lunch', person: '', ...overrides })
assert.equal(parseRupees('150.50'), 15050)
assert.equal(parseRupees('0.01'), 1)
for (const invalid of ['0', '-10', '1.001', '1e3', 'NaN', '', '9007199254740991']) assert.equal(parseRupees(invalid), null)
assert.equal(validateEntry(entry(), []), null)
assert.ok(validateEntry(entry({ date: '2026-02-30' }), []))
assert.ok(validateEntry(entry({ amountPaise: 1.5 }), []))
assert.ok(validateEntry(entry({ kind: 'lent' }), []))
assert.ok(validateEntry(entry(), [entry()]))
const lent = entry({ id: '2', kind: 'lent', person: 'Rahul', amountPaise: 80000 })
const borrowed = entry({ id: '3', kind: 'borrowed', person: 'Rahul', amountPaise: 120000 })
const received = entry({ id: '4', kind: 'repayment-received', person: ' rahul ', amountPaise: 30000 })
const paid = entry({ id: '5', kind: 'repayment-paid', person: 'Rahul', amountPaise: 20000 })
assert.equal(validateEntry(received, [lent]), null)
assert.ok(validateEntry(received, []))
assert.ok(validateEntry({ ...received, amountPaise: 80001 }, [lent]))
assert.ok(validateEntry(paid, [lent]))
assert.equal(validateEntry(paid, [borrowed]), null)
assert.deepEqual(balances([lent, borrowed, received, paid]), [{ person: 'Rahul', receivablePaise: 50000, payablePaise: 100000 }])
assert.equal(monthlySpending([entry(), lent, borrowed, received, paid, entry({ id: '6', date: '2026-10-01' })], '2026-11'), 15000)
console.log('PASS: exact paise, validation, duplicate saves, directional balances, repayment limits, monthly spending')
