import 'fake-indexeddb/auto'
import assert from 'node:assert/strict'
import { appendEntries, readEntries, acknowledge, budget, entryFromUnknown } from '../src/storage.ts'
import type { Entry } from '../src/ledger.ts'
const entry = (overrides: Partial<Entry> = {}): Entry => ({ id: crypto.randomUUID(), kind: 'expense', amountPaise: 15000, date: '2026-11-16', description: 'Lunch', person: '', ...overrides })
const first = entry()
await appendEntries([first])
assert.equal((await readEntries())[0].synced, false)
await appendEntries([first])
assert.equal((await readEntries()).length, 1)
await assert.rejects(appendEntries([{ ...first, amountPaise: 16000 }]))
const lent = entry({ kind: 'lent', person: 'Rahul', amountPaise: 80000 })
const repayment = entry({ kind: 'repayment-received', person: 'Rahul', amountPaise: 30000 })
await appendEntries([lent, repayment])
const before = (await readEntries()).length
await assert.rejects(appendEntries([entry(), entry({ kind: 'repayment-received', person: 'Unknown' })]))
assert.equal((await readEntries()).length, before, 'batch saves must be atomic')
await acknowledge(first)
assert.equal((await readEntries())[0].synced, true)
await assert.rejects(acknowledge({ ...lent, amountPaise: 1 }))
await assert.rejects(appendEntries([entry({ amountPaise: 1.5 })]))
assert.throws(() => entryFromUnknown({ ...first, id: 'bad-id' }))
assert.throws(() => entryFromUnknown({ ...first, kind: 'repayment-unknown' }))
await budget(100000)
assert.equal(await budget(), 100000)
console.log('PASS: IndexedDB saves, pending queue, duplicate protection, atomic rollback, acknowledgement, input validation, budget')
const accountA = crypto.randomUUID(), accountB = crypto.randomUUID()
await appendEntries([first], false, accountA)
assert.equal((await readEntries(accountA)).length, 1)
assert.equal((await readEntries(accountB)).length, 0)
await budget(25000, accountA)
assert.equal(await budget(undefined, accountB), 0)
assert.equal(await budget(), 100000, 'Legacy guest budget remains intact')
console.log('PASS: account-specific ledger and budget isolation; legacy guest data retained')
